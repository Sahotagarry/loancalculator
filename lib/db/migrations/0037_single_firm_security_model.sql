-- Task 37: additive, staged single-firm security model.
-- Existing clients and document rows are deliberately not adopted. Application
-- authorization must require an adopted, non-quarantined client and complete
-- document ownership before returning either client data or document bytes.

CREATE TABLE IF NOT EXISTS "firms" (
  "id" varchar PRIMARY KEY DEFAULT gen_random_uuid(),
  "tenant_id" text NOT NULL UNIQUE,
  "name" text NOT NULL,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "app_users" (
  "tenant_id" text NOT NULL,
  "object_id" text NOT NULL,
  "firm_id" varchar NOT NULL REFERENCES "firms"("id"),
  "display_name" text,
  "email" text,
  "role" text NOT NULL,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("tenant_id", "object_id"),
  CONSTRAINT "app_users_role_valid"
    CHECK ("role" IN ('admin', 'manager', 'accountant', 'read_only'))
);
CREATE INDEX IF NOT EXISTS "app_users_firm_id_idx" ON "app_users" ("firm_id");

-- Allows this migration to safely upgrade a database where the security
-- tables were provisioned before informational identity claims were added.
ALTER TABLE "app_users"
  ADD COLUMN IF NOT EXISTS "display_name" text,
  ADD COLUMN IF NOT EXISTS "email" text;

ALTER TABLE "clients"
  ADD COLUMN IF NOT EXISTS "firm_id" varchar REFERENCES "firms"("id"),
  ADD COLUMN IF NOT EXISTS "adopted_at" timestamptz,
  ADD COLUMN IF NOT EXISTS "quarantined_at" timestamptz,
  ADD COLUMN IF NOT EXISTS "quarantine_reason" text;

-- Never infer a firm for pre-security data. Quarantine it until an explicit
-- administrative adoption transaction sets firm_id and adopted_at.
UPDATE "clients"
SET "quarantined_at" = now(),
    "quarantine_reason" = COALESCE("quarantine_reason", 'Legacy client requires explicit firm adoption')
WHERE "adopted_at" IS NULL
  AND "quarantined_at" IS NULL;

CREATE INDEX IF NOT EXISTS "clients_firm_adoption_quarantine_idx"
  ON "clients" ("firm_id", "adopted_at", "quarantined_at");

CREATE TABLE IF NOT EXISTS "client_memberships" (
  "client_id" varchar NOT NULL REFERENCES "clients"("id") ON DELETE CASCADE,
  "tenant_id" text NOT NULL,
  "object_id" text NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("client_id", "tenant_id", "object_id"),
  CONSTRAINT "client_memberships_app_user_fkey"
    FOREIGN KEY ("tenant_id", "object_id")
    REFERENCES "app_users"("tenant_id", "object_id")
);
CREATE INDEX IF NOT EXISTS "client_memberships_user_idx"
  ON "client_memberships" ("tenant_id", "object_id");

-- Keep the current bytea fallback intact. Nullable ownership columns make it
-- possible to backfill only after a client is explicitly adopted. The UUID is
-- the internal document handle; callers must not receive raw blob locators.
ALTER TABLE "stored_documents"
  ALTER COLUMN "content" DROP NOT NULL,
  ADD COLUMN IF NOT EXISTS "storage_ref" text,
  ADD COLUMN IF NOT EXISTS "tenant_id" text,
  ADD COLUMN IF NOT EXISTS "firm_id" varchar REFERENCES "firms"("id"),
  ADD COLUMN IF NOT EXISTS "client_id" varchar REFERENCES "clients"("id"),
  ADD COLUMN IF NOT EXISTS "file_id" varchar REFERENCES "files"("id"),
  ADD COLUMN IF NOT EXISTS "uploader_tenant_id" text,
  ADD COLUMN IF NOT EXISTS "uploader_object_id" text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'stored_documents_uploader_fkey'
  ) THEN
    ALTER TABLE "stored_documents"
      ADD CONSTRAINT "stored_documents_uploader_fkey"
      FOREIGN KEY ("uploader_tenant_id", "uploader_object_id")
      REFERENCES "app_users"("tenant_id", "object_id");
  END IF;
END $$;

-- Replace only the FK names generated by the earlier column definitions. The
-- catalog checks confirm each name still points from the expected ownership
-- column to its expected parent before it is dropped.
DO $$
DECLARE
  generated_constraint text;
BEGIN
  FOREACH generated_constraint IN ARRAY ARRAY[
    'stored_documents_client_id_fkey',
    'stored_documents_client_id_clients_id_fk'
  ]
  LOOP
    IF EXISTS (
      SELECT 1
      FROM pg_constraint AS fk
      JOIN pg_attribute AS column_definition
        ON column_definition.attrelid = fk.conrelid
       AND column_definition.attnum = fk.conkey[1]
      WHERE fk.conname = generated_constraint
        AND fk.conrelid = 'stored_documents'::regclass
        AND fk.confrelid = 'clients'::regclass
        AND fk.contype = 'f'
        AND array_length(fk.conkey, 1) = 1
        AND column_definition.attname = 'client_id'
    ) THEN
      EXECUTE format(
        'ALTER TABLE "stored_documents" DROP CONSTRAINT %I',
        generated_constraint
      );
    END IF;
  END LOOP;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'stored_documents_client_id_cascade_fkey'
      AND conrelid = 'stored_documents'::regclass
  ) THEN
    ALTER TABLE "stored_documents"
      ADD CONSTRAINT "stored_documents_client_id_cascade_fkey"
      FOREIGN KEY ("client_id") REFERENCES "clients"("id") ON DELETE CASCADE;
  END IF;
END $$;

DO $$
DECLARE
  generated_constraint text;
BEGIN
  FOREACH generated_constraint IN ARRAY ARRAY[
    'stored_documents_file_id_fkey',
    'stored_documents_file_id_files_id_fk'
  ]
  LOOP
    IF EXISTS (
      SELECT 1
      FROM pg_constraint AS fk
      JOIN pg_attribute AS column_definition
        ON column_definition.attrelid = fk.conrelid
       AND column_definition.attnum = fk.conkey[1]
      WHERE fk.conname = generated_constraint
        AND fk.conrelid = 'stored_documents'::regclass
        AND fk.confrelid = 'files'::regclass
        AND fk.contype = 'f'
        AND array_length(fk.conkey, 1) = 1
        AND column_definition.attname = 'file_id'
    ) THEN
      EXECUTE format(
        'ALTER TABLE "stored_documents" DROP CONSTRAINT %I',
        generated_constraint
      );
    END IF;
  END LOOP;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'stored_documents_file_id_cascade_fkey'
      AND conrelid = 'stored_documents'::regclass
  ) THEN
    ALTER TABLE "stored_documents"
      ADD CONSTRAINT "stored_documents_file_id_cascade_fkey"
      FOREIGN KEY ("file_id") REFERENCES "files"("id") ON DELETE CASCADE;
  END IF;
END $$;

-- NOT VALID preserves any unexpected legacy row while enforcing exactly one
-- private storage backend for all subsequently inserted or updated documents.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'stored_documents_exactly_one_backend'
  ) THEN
    ALTER TABLE "stored_documents"
      ADD CONSTRAINT "stored_documents_exactly_one_backend"
      CHECK (("content" IS NULL) <> ("storage_ref" IS NULL)) NOT VALID;
  END IF;
END $$;

